// Reads .claude/agents/*.md (active) and .claude/agents-parked/*.md (parked) and writes
// ../agents-office/agents.generated.js so the dashboard
// always shows each agent's real tools, model and instructions.
//   npm run dashboard
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const out_dir = '../agents-office';
const agents = {};
const sources = [['.claude/agents', false], ['.claude/agents-parked', true]];

for (const [dir, parked] of sources) for (const name of readdirSync(dir).filter((f) => f.endsWith('.md'))) {
  const text = readFileSync(join(dir, name), 'utf8');
  const [, front = '', body = ''] = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/) ?? [];
  const meta = Object.fromEntries(
    front.split('\n').map((line) => line.match(/^(\w+):\s*(.*)$/)).filter(Boolean).map(([, k, v]) => [k, v])
  );
  agents[name.replace(/\.md$/, '')] = {
    description: meta.description ?? '',
    model: meta.model ?? 'inherit',
    tools: (meta.tools ?? '').split(',').map((t) => t.trim()).filter(Boolean),
    instructions: body.trim(),
    parked,
  };
}

const out = `// Generated by scripts/build-dashboard.mjs from .claude/agents/*.md. Do not edit.\n` +
  `window.AGENTS = ${JSON.stringify(agents, null, 2)};\n`;
writeFileSync(`${out_dir}/agents.generated.js`, out);

if (!existsSync(`${out_dir}/status.js`)) {
  writeFileSync(`${out_dir}/status.js`, 'window.STATUS = { run: null, agents: {} };\n');
}
console.log(`Dashboard data updated for ${Object.keys(agents).length} agents.`);
console.log('Written to ../agents-office/agents.generated.js');
